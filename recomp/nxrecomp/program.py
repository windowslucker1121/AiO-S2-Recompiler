def make_env(spec):
    """Rebuild an Env in a worker from a picklable spec."""
    img = open_image(spec)
    from .config import load_game
    cfg = load_game(spec.get('game'))
    env = Env(img, cfg)
    env.module_index = module_index_of(cfg, spec)
    if spec.get('patches'):
        env.patches = load_patches(spec['patches'], img)
    if spec.get('sites'):
        load_sites(spec['sites'], env)
    env.ends = dict(spec['ends'])
    env.starts = sorted(env.ends)
    env.jt = {int(k): v for k, v in spec['jt'].items()}
    env.tailbr = set(spec.get('tailbr', ()))
    env.pads = spec['pads']
    env.catchers = set(spec['catchers'])
    env.scratch_optout = set(spec.get('scratch_optout', ()))
    env.scratch_store = set(spec.get('scratch_store', ()))
    env.scratch_known = bool(spec.get('scratch_known'))
    env.full = True
    return env


def module_index_of(cfg, spec):
    """NxModule.index: --index, else the position of the module in the game config's list, else 0."""
    if spec.get('index') is not None:
        return int(spec['index'])
    for i, m in enumerate(cfg.modules):
        if m.name == spec.get('name'):
            return i
    return 0


def open_image(spec):
    k = spec['kind']
    if k == 'nso':
        return Image.from_nso(open(spec['path'], 'rb').read(), spec['base'], spec['name'])
    if k == 'nx_elf':
        return Image.from_nx_elf(spec['path'], spec['base'], spec['name'])
    return Image.from_static_elf(spec['path'], spec['name'])


_worker_env = None


def _worker_init(spec):
    global _worker_env
    _worker_env = make_env(spec)


def _worker_scan(entries):
    """entries: [(entry, end or None)]; an end given here replaces the one the worker's spec has (discovery shortens them)."""
    env = _worker_env
    env.wanted = collections.OrderedDict()
    total = bad = 0
    for a, end in entries:
        if end is not None:
            env.ends[a] = end
        _, n, b, _ = lift_function(env, a)
        total += n
        bad += len(b)
    return total, bad, list(env.wanted)


def _worker_scratch(entries):
    """Scratch-register liveness of the given functions (see scratch_liveness): (entry, live at entry?, live after a call?, stub?)."""
    env = _worker_env
    env.wanted = collections.OrderedDict()
    out = []
    for a in entries:
        t, n, _, _ = _lift_function(env, a)
        if n == 0:                                    # an import / alias stub: its callee is unknown here
            out.append((a, False, False, True))
            continue
        ein, aft = scratch_liveness(t)
        out.append((a, bool(ein), bool(aft), False))
    return out


def _worker_text(entries):
    env = _worker_env
    env.wanted = collections.OrderedDict()
    texts, resume, insns = [], [], 0
    for a in entries:
        t, n, _, r = lift_function(env, a)
        texts.append(t)
        resume += r
        insns += n
    return '\n\n'.join(texts), resume, insns


def _write_if_changed(path, content):
    if os.path.exists(path):
        with open(path, encoding='utf-8', newline='') as f:
            if f.read() == content:
                return False
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(content)
    return True


def lift_module(spec, outdir, jobs=8, shards=0, bucket=0xC000, log=print):
    """Lift every function of the module described by `spec` into outdir.
    spec: dict(kind, path, base, name, game, patches). shards > 0: exactly that many c_NNN.cpp files (balanced by
    instruction count, contiguous in address order); shards == 0: one c_<bucket>.cpp per `bucket` bytes of guest code."""
    from .config import load_game
    t0 = time.time()
    img = open_image(spec)
    cfg = load_game(spec.get('game'))
    env = Env(img, cfg)
    env.module_index = module_index_of(cfg, spec)
    if spec.get('patches'):
        env.patches = load_patches(spec['patches'], img)
    if spec.get('sites'):
        load_sites(spec['sites'], env)
    env.compute_starts()
    for a in sorted(env.sites['midhook']):                 # a mid-function hook makes its address a function of its own
        if a not in env.ends:
            env.ends[a] = env.extent(a)
    env.starts = sorted(env.ends)
    env.load_eh()
    n_setjmp = env.add_setjmp_pads()
    if n_setjmp:
        log('%s: %d setjmp calls (their return addresses are landing pads)' % (img.name, n_setjmp))
    from . import jumptables
    jumptables.resolve(env)
    starts = env.starts
    log('%s: %d function entries, %d landing pads, %d jump tables  (%.1fs)' % (img.name, len(starts), len(env.pads), len(env.jt), time.time() - t0))
    spec = dict(spec, ends=env.ends, jt={str(k): v for k, v in env.jt.items()}, tailbr=sorted(env.tailbr), pads=env.pads, catchers=sorted(env.catchers))
    os.makedirs(outdir, exist_ok=True)
    known = set(starts)
    pending = list(starts)
    all_funcs, total, bad = [], 0, 0
    pool = multiprocessing.Pool(jobs, _worker_init, (spec,)) if jobs > 1 else None
    if pool is None:
        _worker_init(spec)
    try:
        mapper = pool.imap_unordered if pool else map
        # discovery: lifting finds branch targets that are not listed functions (tail calls, fall-through ends).
        # A found entry has no exact end (no FDE covers it): it ends at the next known entry and falls through into it. Each round can
        # find entries inside earlier found ones (code without unwind tables); those shrink and are scanned again, so no stretch of
        # code is lifted into more than one function.
        found, listed = set(), set()
        while pending:
            pending.sort()
            parts = [[(a, env.ends.get(a) if a in found else None) for a in pending[i:i + 400]] for i in range(0, len(pending), 400)]
            new = set()
            for n, b, wanted in mapper(_worker_scan, parts):
                total += n
                bad += b
                new.update(w for w in wanted if w not in known and env.text_lo <= w < env.text_hi)
            all_funcs += [a for a in pending if a not in listed]
            listed.update(pending)
            log('discovery: %d functions, %d extra branch targets  (%.1fs)' % (len(pending), len(new), time.time() - t0))
            known |= new
            found |= {w for w in new if w not in env.ends}
            order = sorted(known)
            again = []
            for a in found:
                i = bisect.bisect_right(order, a)
                end = order[i] if i < len(order) else env.text_hi
                if env.ends.get(a) != end:
                    if a in env.ends and a not in new:
                        again.append(a)
                    env.ends[a] = end
            pending = sorted(new | set(again))
        all_funcs.sort()
        # workers must know the new entries too (their extents are by the next start): rebuild the spec
        if len(all_funcs) != len(starts):
            spec['ends'] = {a: env.ends.get(a, env.extent(a)) for a in all_funcs}
            if pool:
                pool.close()
                pool = multiprocessing.Pool(jobs, _worker_init, (spec,))
                mapper = pool.imap_unordered
            else:
                _worker_init(spec)
        if scratch_locals_on(env):
            optout, store = set(), set()
            parts = [all_funcs[i:i + 400] for i in range(0, len(all_funcs), 400)]
            for part in mapper(_worker_scratch, parts):
                for a, ein, aft, stub in part:
                    if aft:
                        optout.add(a)
                    if ein or stub:
                        store.add(a)
            spec['scratch_optout'], spec['scratch_store'], spec['scratch_known'] = sorted(optout), sorted(store), True
            log('scratch registers: %d functions keep them in the context, %d callees get them stored before a call  (%.1fs)'
                % (len(optout), len(store), time.time() - t0))
            if pool:
                pool.close()
                pool = multiprocessing.Pool(jobs, _worker_init, (spec,))
                mapper = pool.imap_unordered
            else:
                _worker_init(spec)
        # shard assignment
        sizes = {a: max(1, (spec['ends'][a] - a) // 4) for a in all_funcs}
        groups = collections.OrderedDict()
        if shards:
            target = sum(sizes.values()) / float(shards)
            k, acc = 0, 0
            for a in all_funcs:
                if acc >= target and k < shards - 1:
                    k, acc = k + 1, 0
                groups.setdefault(k, []).append(a)
                acc += sizes[a]
            names = {k: 'c_%03d.cpp' % k for k in range(shards)}
            for k in range(shards):
                groups.setdefault(k, [])
        else:
            for a in all_funcs:
                groups.setdefault((a - env.base) // bucket, []).append(a)
            names = {k: 'c_%04x.cpp' % k for k in groups}
        jobs_list = [(k, v) for k, v in groups.items()]
        resume, files, changed, insns = [], [], 0, 0
        for (k, entries), (text, res, n) in zip(jobs_list, map_ordered(pool, _worker_text, [v for _, v in jobs_list])):
            resume += res
            insns += n
            content = GEN_HEADER + text + '\n'
            files.append(names[k])
            changed += _write_if_changed(os.path.join(outdir, names[k]), content)
    finally:
        if pool:
            pool.close()
    first = {}
    for lp, e in sorted(resume):
        first.setdefault(lp, e)
    resume = sorted(first.items())
    catchers = sorted(a for a in env.catchers if a in set(all_funcs))
    write_module_files(env, outdir, all_funcs, resume, catchers)
    keep = set(files) | {'funcs.h', 'module_%s.cpp' % img.name}
    for n in os.listdir(outdir):
        if (n.endswith('.cpp') and n.startswith('c_')) and n not in keep:
            os.remove(os.path.join(outdir, n))
    log('%s: functions %d   files %d (%d rewritten)   instructions %d   not translated %d   (%.1fs)'
        % (img.name, len(all_funcs), len(files), changed, insns, bad, time.time() - t0))
    return {'functions': len(all_funcs), 'files': files, 'instructions': insns, 'not_translated': bad}


def map_ordered(pool, fn, items):
    return pool.map(fn, items) if pool else [fn(i) for i in items]


def write_module_files(env, outdir, all_funcs, resume, catchers):
    img = env.img
    name = mangle(img.name)
    nsym = img.nsym if img.symtab_is_dynamic else 0
    u_entries = sorted(set(e for _, e in resume) | set(catchers))
    h = ['/* generated by nxrecomp -- do not edit */', '#ifndef NXRECOMP_FUNCS_H', '#define NXRECOMP_FUNCS_H',
         '#include <nxrecomp/ctx.h>', '#ifdef __cplusplus', 'extern "C" {', '#endif',
         '#define NX_OPTNONE __attribute__((optnone, noinline))']
    h += ['void f_%x(Ctx *__restrict c);' % a for a in all_funcs]
    h += ['void u_%x(Ctx *__restrict c, uint64_t rp);' % a for a in u_entries]
    h += ['void h_%s(Ctx *c);' % n for n in sorted(set(env.overrides.values()))]
    h += ['#ifdef __cplusplus', '}', '#endif', '#endif', '']
    _write_if_changed(os.path.join(outdir, 'funcs.h'), '\n'.join(h))
    m = ['/* generated by nxrecomp -- do not edit */', '#include <nxrecomp/ctx.h>', '#include "funcs.h"', '',
         'extern "C" {', 'static const FnEntry fns[] = {']
    m += ['  { 0x%xULL, f_%x },' % (a, a) for a in all_funcs]
    for a, n in sorted(env.overrides.items()):
        m.append('  { 0x%xULL, h_%s },' % (a, n))
    m.append('};')
    m.append('static const DynSym syms[] = {')
    allsyms = img.symbols() if nsym else []
    for i in range(nsym):
        sname, typ, bind, shndx, value, size = allsyms[i]
        # value: guest ADDRESS of a defined symbol (an NSO's module-relative st_value gets the module base added, a static
        # ELF's is absolute already); 0 for an undefined one; a thread-local symbol (STT_TLS) keeps its raw st_value (a TLS offset)
        if not shndx:
            value = 0
        elif typ != 6 and shndx != 0xfff1:            # not thread-local, not SHN_ABS
            value = img.base + img.sym_value(value)
        m.append('  { "%s", 0x%xULL, %d },' % (sname.replace('\\', '\\\\').replace('"', '\\"'), value, 1 if shndx else 0))
    if not nsym:
        m.append('  { "", 0, 0 },')
    m.append('};')
    m.append('static const NxResume resume[] = {')
    m += ['  { 0x%xULL, u_%x },' % (lp, e) for lp, e in resume]
    if not resume:
        m.append('  { 0, 0 },')
    m.append('};')
    eh_name = emit_eh_tables(env, m)
    m.append('extern const NxModule nxmod_%s;' % name)
    m.append('extern const uint32_t nxmod_%s_abi;' % name)
    m.append('const uint32_t nxmod_%s_abi = NXRECOMP_ABI_VERSION;' % name)
    m.append('const NxModule nxmod_%s = { "%s", %du, 0x%xULL, 0x%xULL, fns, %d, syms, %d, resume, %d, %s };'
             % (name, img.name, env.module_index, env.base, env.text_hi, len(all_funcs) + len(env.overrides), nsym, len(resume), eh_name))
    m.append('}')
    m.append('')
    _write_if_changed(os.path.join(outdir, 'module_%s.cpp' % name), '\n'.join(m))


def img_sym(img, i):
    name_off, info, other, shndx, value, size = struct.unpack_from('<IBBHQQ', img.mem, img.sym_off + i * 24)
    return img.cstr(img.str_off + name_off), info & 0xf, info >> 4, shndx, value, size


def emit_eh_tables(env, m):
    """Append the NxEh tables of the module to m (unwind rows, call sites, actions, types) -> expression for NxModule.eh."""
    from . import ehtables
    return ehtables.emit(env, m)


# ---------------------------------------------------------------------------------------------------- coverage
def cover(img, cfg=None, log=print, limit_examples=3):
    """Per-instruction-word translation coverage of .text, with the reasons for what is not translated."""
    env = Env(img, cfg)
    fn = Lifter(img.base, img.end, env)
    ok = bad = 0
    reasons = collections.Counter()
    examples = {}
    cache = {}
    for i, w in enumerate(img.words()):
        r = cache.get(w)
        if r is None:
            try:
                fn.lift(w, env.text_lo + 0x1000000)
                r = ''
            except Unimpl as e:
                r = str(e)
            except Exception as e:                       # a decoder bug counts as not translated
                r = 'error:%s' % type(e).__name__
            cache[w] = r
        if r:
            bad += 1
            reasons[r] += 1
            examples.setdefault(r, '%x:%08x' % (env.text_lo + 4 * i, w))
        else:
            ok += 1
    total = ok + bad
    log('instruction words: %d   translated: %d (%.2f%%)   not translated: %d (%.2f%%)'
        % (total, ok, 100.0 * ok / max(1, total), bad, 100.0 * bad / max(1, total)))
    for r, n in reasons.most_common(30):
        log('  %-16s %9d  %.2f%%   e.g. %s' % (r, n, 100.0 * n / total, examples[r]))
    return ok, bad, reasons
