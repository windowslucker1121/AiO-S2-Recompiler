#!/usr/bin/env python3
"""Generate the NVN2 entry-point table and the NVN2 struct-size table (title A, SDK_NVN-20_5_25).

Inputs (relative to the repo root that contains this scripts/ folder):
  src/gfx/nvn/nvn2_procs.tsv  one row per proc of the sdk's GetProcAddress table (written by the analysis tooling,
                              see docs/nvn2_abi.md "How the tables were made")
  src/gfx/nvn/nvn_table.inc   the NVN1 table, to check every row classified 'same' / 'changed-sig' / 'new'
Outputs:
  src/gfx/nvn/nvn2_table.inc  one NVN2_ENTRY(name, ret, args, sdk_addr, flags) line per proc
  src/gfx/nvn/nvn2_sizes.inc  one NVN2_STRUCT(name, min_size, max_size, nvn1_size, source_mask) line per struct

Optional: --sdk <sdk.elf> (the game's sdk NSO converted to ELF by nx2elf) re-reads the 726 proc names and function
addresses from the sdk's own GetProcAddress tables and fails if the TSV disagrees.

Run:
  python -I scripts/gen_nvn2_table.py [--sdk <path of sdk.elf>]

Standard library only. Output is deterministic: no timestamps, fixed orders, LF endings. Exit code 1 on any check failure.
"""

import argparse
import os
import re
import struct
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(SCRIPT_DIR)
NVN_DIR = os.path.join(REPO_ROOT, "src", "gfx", "nvn")
TSV = os.path.join(NVN_DIR, "nvn2_procs.tsv")
NVN1_TABLE = os.path.join(NVN_DIR, "nvn_table.inc")
HEADER = "// GENERATED by scripts/gen_nvn2_table.py from src/gfx/nvn/nvn2_procs.tsv (see docs/nvn2_abi.md): do not edit"

# Where the sdk keeps its proc table (sdk build cc7da00d672399efe7958790d17fae396b1fde9f, SDK_NVN-20_5_25).
# nvnDeviceGetProcAddress (0x5DBD00) binary-searches NAME_OFFS (u32 offsets from NAME_BASE, names without the "nvn"
# prefix, sorted) and returns FN_TABLE[index]; FN_TABLE entries are RELR relocations, so the file holds the target.
SDK_COUNT = 0x2D6
SDK_NAME_OFFS = 0xBA1D88
SDK_NAME_BASE = 0xB9CA26
SDK_FN_TABLE = 0xE056E0

# NVN2 object sizes. min = bytes the sdk itself touches or clears (safe for the back end to use), max = room the game
# leaves for the object (its own next field / stack frame / array stride). source_mask: 1 = sdk code, 2 = game code,
# 4 = settled (min == max by evidence of the game's layout). Evidence for every row: docs/nvn2_abi.md "Struct sizes".
#        name                         min     max     nvn1   mask
STRUCTS = [
    ("NVNdevice",                    0x22D8, 0x3000, 0x3000, 2 | 4),
    ("NVNdeviceBuilder",             0x18,   0x40,   0x40,   1 | 2 | 4),
    ("NVNqueue",                     0x2CC8, 0x3000, 0x2000, 1 | 2 | 4),
    ("NVNqueueBuilder",              0x48,   0x50,   0x40,   1 | 2),
    ("NVNwindow",                    0x218,  0x280,  0x180,  1 | 2),
    ("NVNwindowBuilder",             0x60,   0x80,   0x40,   1 | 2 | 4),
    ("NVNmemoryPool",                0x100,  0x100,  0x100,  1 | 2 | 4),
    ("NVNmemoryPoolBuilder",         0x38,   0x40,   0x40,   1 | 2 | 4),
    ("NVNbuffer",                    0x30,   0x38,   0x30,   1 | 2),
    ("NVNbufferBuilder",             0x28,   0x40,   0x40,   1 | 2 | 4),
    ("NVNtexture",                   0x80,   0xC0,   0x80,   1 | 2 | 4),
    ("NVNtextureBuilder",            0x68,   0x80,   0x80,   1 | 2 | 4),
    ("NVNtextureView",               0x10,   0x10,   0x10,   1 | 2 | 4),
    ("NVNsampler",                   0x40,   0x68,   0x40,   1 | 2),
    ("NVNsamplerBuilder",            0x30,   0x40,   0x40,   1 | 2 | 4),
    ("NVNtexturePool",               0x20,   0x28,   0x20,   1 | 2),
    ("NVNsamplerPool",               0x20,   0x28,   0x20,   1 | 2),
    ("NVNprogram",                   0xA0,   0xC0,   0x80,   1 | 2),
    ("NVNsync",                      0x20,   0x40,   0x40,   1 | 2 | 4),
    ("NVNcommandBuffer",             0xB0,   0xC0,   0xA0,   1 | 2),
    ("NVNevent",                     0x28,   0,      0x40,   1),
    ("NVNeventBuilder",              0x10,   0,      0x20,   1),
    ("NVNblendState",                0x8,    0,      0x8,    1),
    ("NVNchannelMaskState",          0x4,    0,      0x4,    1),
    ("NVNcolorState",                0x4,    0,      0x4,    1),
    ("NVNdepthStencilState",         0x8,    0,      0x8,    1),
    ("NVNmultisampleState",          0x18,   0,      0x18,   1),
    ("NVNpolygonState",              0x4,    0,      0x4,    1),
    ("NVNvertexAttribState",         0x4,    0x4,    0x4,    1 | 2 | 4),
    ("NVNvertexStreamState",         0x8,    0,      0x8,    1),
    ("NVNcopyRegion",                0x18,   0,      0x18,   1),
    ("NVNshaderData",                0x10,   0x10,   0x10,   1 | 4),
    ("NVNshaderDataExt",             0x18,   0x18,   0,      1 | 4),
    ("NVNprogramBuilder",            0x64,   0,      0,      1),
    ("NVNdeviceCommandBuffer",       0x30,   0,      0,      1),
    ("NVNdeviceMessageBuffer",       0x28,   0,      0,      1),
    ("NVNdirtyTileMapParameters",    0x74,   0,      0,      1),
    ("NVNdlssNetwork",               0x220,  0,      0,      1),
    ("NVNdlssNetworkBuilder",        0xB8,   0,      0,      1),
    ("NVNdlssParameters",            0xC0,   0,      0,      1),
]

CLASS_BITS = {"same": 0, "changed-sig": 1, "new": 2}
COLUMNS = ["idx", "name", "sdk_addr", "ret", "args", "sig_source", "nvn1_ret", "nvn1_args", "hexrays_nargs", "class",
           "note", "main_code_refs", "main_use"]


def fail(errors, msg):
    errors.append(msg)


def read_tsv(path):
    rows = []
    with open(path, encoding="utf-8") as f:
        lines = [ln.rstrip("\n") for ln in f if not ln.startswith("#")]
    if lines[0].split("\t") != COLUMNS:
        raise SystemExit("unexpected TSV header: %r" % lines[0])
    for ln in lines[1:]:
        if ln:
            rows.append(dict(zip(COLUMNS, ln.split("\t"))))
    return rows


def read_nvn1(path):
    text = open(path, encoding="utf-8").read()
    return {m.group(1): (m.group(2), m.group(3))
            for m in re.finditer(r'NVN_ENTRY\("(\w+)", \'(\w)\', "(\w*)"', text)}


class ElfImage:
    """Just enough ELF64 to read virtual addresses of the nx2elf output."""

    def __init__(self, path):
        self.data = open(path, "rb").read()
        if self.data[:4] != b"\x7fELF" or self.data[4] != 2:
            raise SystemExit("not an ELF64 file: " + path)
        phoff, = struct.unpack_from("<Q", self.data, 0x20)
        phentsize, phnum = struct.unpack_from("<HH", self.data, 0x36)
        self.segs = []
        for i in range(phnum):
            p_type, _, p_offset, p_vaddr, _, p_filesz, _, _ = struct.unpack_from("<IIQQQQQQ", self.data, phoff + i * phentsize)
            if p_type == 1:
                self.segs.append((p_vaddr, p_filesz, p_offset))

    def read(self, va, n):
        for vaddr, filesz, off in self.segs:
            if vaddr <= va and va + n <= vaddr + filesz:
                return self.data[off + va - vaddr: off + va - vaddr + n]
        raise SystemExit("address 0x%X not in a loaded segment" % va)

    def cstr(self, va):
        out = bytearray()
        while True:
            b = self.read(va + len(out), 1)
            if b == b"\0":
                return out.decode("ascii")
            out += b


def check_sdk(rows, path, errors):
    elf = ElfImage(path)
    if len(rows) != SDK_COUNT:
        fail(errors, "TSV has %d rows, the sdk table %d" % (len(rows), SDK_COUNT))
    for i in range(SDK_COUNT):
        off, = struct.unpack("<I", elf.read(SDK_NAME_OFFS + 4 * i, 4))
        name = "nvn" + elf.cstr(SDK_NAME_BASE + off)
        fn, = struct.unpack("<Q", elf.read(SDK_FN_TABLE + 8 * i, 8))
        if i >= len(rows):
            break
        r = rows[i]
        if r["name"] != name or int(r["sdk_addr"], 16) != fn:
            fail(errors, "sdk row %d is %s @0x%X, TSV says %s @%s" % (i, name, fn, r["name"], r["sdk_addr"]))
    print("Checked %d names and addresses against %s" % (SDK_COUNT, path))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdk", help="sdk.elf (nx2elf output) to re-check names and addresses")
    args = ap.parse_args()

    rows = read_tsv(TSV)
    nvn1 = read_nvn1(NVN1_TABLE)
    errors = []

    names = [r["name"] for r in rows]
    if len(set(names)) != len(names):
        fail(errors, "duplicate names in the TSV")
    if [int(r["idx"]) for r in rows] != list(range(len(rows))):
        fail(errors, "idx column is not 0..n-1")
    if [n[3:] for n in names] != sorted(n[3:] for n in names):
        fail(errors, "rows are not in the sdk's sorted order")
    for r in rows:
        n, c = r["name"], r["class"]
        if c not in CLASS_BITS:
            fail(errors, "%s: unknown class %s" % (n, c))
            continue
        if not re.fullmatch(r"[vilpfdS]", r["ret"]) or not re.fullmatch(r"[ilpfdS]*", r["args"]):
            fail(errors, "%s: bad signature %r %r" % (n, r["ret"], r["args"]))
        if c == "same" and nvn1.get(n) != (r["ret"], r["args"]):
            fail(errors, "%s: 'same' but differs from the NVN1 table %s" % (n, nvn1.get(n)))
        if c == "changed-sig" and (n not in nvn1 or nvn1[n] == (r["ret"], r["args"])):
            fail(errors, "%s: 'changed-sig' but NVN1 table has %s" % (n, nvn1.get(n)))
        if c == "new" and n in nvn1:
            fail(errors, "%s: 'new' but present in the NVN1 table" % n)
        if (int(r["main_code_refs"]) > 0) != (r["main_use"] == "used"):
            fail(errors, "%s: main_use disagrees with main_code_refs" % n)
    if args.sdk:
        check_sdk(rows, args.sdk, errors)

    table = [
        HEADER,
        "// Columns: NVN2_ENTRY(name, ret_class, arg_classes, sdk_address, flags).",
        "// flags: bit0 = main.elf calls it (code reference outside nvnLoadCProcs); bits1-2 = 0 same as NVN1, 1 signature changed, 2 not in the NVN1 table.",
        "// Signatures of 'not in the NVN1 table' rows come from Hex-Rays unless docs/nvn2_abi.md lists them as verified.",
    ]
    for r in rows:
        flags = (1 if r["main_use"] == "used" else 0) | (CLASS_BITS[r["class"]] << 1)
        table.append('NVN2_ENTRY("%s", \'%s\', "%s", 0x%X, %d)' % (r["name"], r["ret"], r["args"], int(r["sdk_addr"], 16), flags))

    sizes = [
        HEADER,
        "// Columns: NVN2_STRUCT(name, min_size, max_size, nvn1_size, source_mask). max/nvn1 0 = unknown.",
        "// min: bytes the sdk itself touches (safe for the back end); max: room the game leaves. source_mask 1 = sdk code, 2 = game code, 4 = settled.",
    ]
    for name, lo, hi, n1, mask in STRUCTS:
        if hi and lo > hi:
            fail(errors, "%s: min 0x%X > max 0x%X" % (name, lo, hi))
        sizes.append('NVN2_STRUCT("%s", 0x%X, 0x%X, 0x%X, %d)' % (name, lo, hi, n1, mask))

    if errors:
        for e in errors:
            print("ERROR: " + e, file=sys.stderr)
        return 1

    for fname, lines in (("nvn2_table.inc", table), ("nvn2_sizes.inc", sizes)):
        with open(os.path.join(NVN_DIR, fname), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")

    count = {k: sum(1 for r in rows if r["class"] == k) for k in CLASS_BITS}
    used = sum(1 for r in rows if r["main_use"] == "used")
    print("Procs: %d (same %d, changed-sig %d, new %d); used by main %d, unused %d"
          % (len(rows), count["same"], count["changed-sig"], count["new"], used, len(rows) - used))
    print("Wrote %s (%d entries) and %s (%d structs)"
          % (os.path.join(NVN_DIR, "nvn2_table.inc"), len(rows), os.path.join(NVN_DIR, "nvn2_sizes.inc"), len(STRUCTS)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
